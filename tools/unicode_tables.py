#!/usr/bin/env python3
"""Writes packages/std-text/src/unicode.av: one run table over every code
point, each run's class folding the grapheme break, the conjunct break,
the emoji flags and the terminal width. Needs the `regex` module, which
carries the Unicode data; the committed file is the artifact.

    python3 tools/unicode_tables.py          # write the table
    python3 tools/unicode_tables.py --check  # fail when the file differs
"""
import sys
import unicodedata

import regex

OUT = "packages/std-text/src/unicode.av"
LAST = 0x10FFFF

# Unassigned code points are wide only inside the ideograph blocks (EastAsianWidth.txt).
UNASSIGNED_WIDE = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
       "SpacingMark", "L", "V", "T", "LV", "LVT"]
PICT, CONSONANT, LINKER, INCB_EXTEND, EMOJI = 16, 32, 64, 128, 256
WIDTH_SHIFT = 9


def probe(pattern):
    return regex.compile(pattern).match


def cell_width(c, ch, wide, emoji_presentation):
    cat = unicodedata.category(ch)
    if c == 0x00AD:
        return 1
    if cat in ("Cc", "Cf", "Mn", "Me", "Zl", "Zp") or 0x1160 <= c <= 0x11FF:
        return 0
    if cat == "Cn":
        return 2 if any(lo <= c <= hi for lo, hi in UNASSIGNED_WIDE) else 1
    if wide(ch) or emoji_presentation(ch):
        return 2
    return 1


def classes():
    gcb = [probe(r"\p{GCB=%s}" % n) for n in GCB]
    pict = probe(r"\p{Extended_Pictographic}")
    consonant = probe(r"\p{InCB=Consonant}")
    linker = probe(r"\p{InCB=Linker}")
    incb_extend = probe(r"\p{InCB=Extend}")
    emoji = probe(r"\p{Emoji}")
    wide = probe(r"[\p{East_Asian_Width=W}\p{East_Asian_Width=F}]")
    emoji_presentation = probe(r"\p{Emoji_Presentation}")
    out = []
    for c in range(LAST + 1):
        ch = chr(c)
        if 0xD800 <= c <= 0xDFFF:
            out.append(0)
            continue
        v = next(i for i, m in enumerate(gcb) if i and m(ch)) if any(m(ch) for m in gcb[1:]) else 0
        v |= PICT if pict(ch) else 0
        v |= CONSONANT if consonant(ch) else 0
        v |= LINKER if linker(ch) else 0
        v |= INCB_EXTEND if incb_extend(ch) else 0
        v |= EMOJI if emoji(ch) else 0
        v |= cell_width(c, ch, wide, emoji_presentation) << WIDTH_SHIFT
        out.append(v)
    return out


def runs(values):
    starts, vals = [], []
    for c, v in enumerate(values):
        if not vals or vals[-1] != v:
            starts.append(c)
            vals.append(v)
    return starts, vals


def rows(name, xs):
    body = "".join("    " + ", ".join(str(x) for x in xs[i:i + 12]) + ",\n" for i in range(0, len(xs), 12))
    return "const %s: List<int> = [\n%s]\n" % (name, body)


def render():
    starts, vals = runs(classes())
    head = (
        "//! Generated by tools/unicode_tables.py from Unicode 17.0 (python `regex`) — do not edit.\n"
        "//!\n"
        "//! One run table over every code point: `run_starts[i]` begins a run whose\n"
        "//! class is `run_classes[i]`. A class folds, from the low bit up: the grapheme\n"
        "//! break (4 bits), Extended_Pictographic (16), InCB Consonant (32), Linker (64),\n"
        "//! Extend (128), Emoji (256) and the terminal width, 0..2 (from bit 9).\n"
    )
    return head + "\n" + rows("run_starts", starts) + "\n" + rows("run_classes", vals)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
    print("%s: %d runs" % (OUT, text.count(",") // 2))
