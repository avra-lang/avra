#!/usr/bin/env python3
"""THE REPORTER: a PURE PROJECTION of the stored JSON rows into markdown
and HTML. It generates no measurement and reads no clock, so the same
`results/runs.jsonl` renders byte-identically every time — the property
the self-test holds.

    report.py [--out DIR] [--check]

`--check` regenerates into a temporary directory and refuses unless it
equals the committed report, which is the reproducibility receipt.
"""
import json
import os
import sys

from bench import BENCH, bench_dirs, registry, spec_of

RESULTS = os.path.join(BENCH, "results", "runs.jsonl")
REPORT = os.path.join(BENCH, "report")


def load_runs(path=RESULTS):
    rows = []
    if not os.path.isfile(path):
        return rows
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def run_map(rows):
    """(benchmark, language, machine) -> the stored row."""
    out = {}
    for row in rows:
        out[(row["benchmark"], row["language"], row["machine"])] = row
    return out


# ── formatting ───────────────────────────────────────────────────────

def human_bytes(v):
    for unit, n in (("MB", 1 << 20), ("kB", 1 << 10)):
        if v >= n:
            return f"{v / n:.1f} {unit}"
    return f"{v:.0f} B"


def fmt(unit, value, samples):
    if unit == "ns":
        if value < 1000:
            shown = f"{value:.1f} ns"
        elif value < 1e6:
            shown = f"{value / 1e3:.2f} µs"
        else:
            shown = f"{value / 1e6:.2f} ms"
    elif unit == "bytes":
        shown = human_bytes(value)
    elif unit == "ops":
        shown = f"{value:,.0f} ops"
    else:
        shown = f"{value:g} {unit}"
    return f"{shown} ({samples})"


def language_titles(reg):
    return {name: cfg.get("title", name) for name, cfg in reg["languages"].items()}


def versions_by_machine(runs, reg):
    """(machine, language) -> version, and the language order the registry
    names. The version is the last one stored, so a stale row names
    itself."""
    versions = {}
    for row in runs:
        if row.get("version") and row["version"] != "unknown":
            versions[(row["machine"], row["language"])] = row["version"]
    return versions


# ── markdown ─────────────────────────────────────────────────────────

HEADER = """# Avra benchmark report

_GENERATED by `benchmarks/run.sh --report` from
`benchmarks/results/runs.jsonl`. Never hand-edit: edit a `spec.toml` or a
language's program and run `--record` again._

The suite measures concurrency and task primitives across languages.
Every language's twin for one benchmark must satisfy the SAME invariant,
written in its `spec.toml`; the rows differ only in what is timed. A
value is the run's own report — typically the least of the program's
`samples` rounds — and the sample count stands beside it. A versionless
number is a claim, so every row carries its toolchain and machine.

See `benchmarks/README.md` for the JSON schema, the row contract, and how
to add a benchmark or a language.
"""


def machine_sections(runs, reg, benches):
    """One section per machine: its versions, then one table per
    benchmark, rows in spec order and languages in spec order."""
    runs_by = run_map(runs)
    titles = language_titles(reg)
    versions = versions_by_machine(runs, reg)
    machines = sorted({row["machine"] for row in runs})
    lines = []
    for machine in machines:
        lines.append(f"## Machine `{machine}`\n")
        lines.append("| language | version |")
        lines.append("|---|---|")
        for lang in reg["languages"]:
            v = versions.get((machine, lang))
            if v:
                lines.append(f"| {titles.get(lang, lang)} | `{v}` |")
        lines.append("")
        for key, bdir in benches:
            spec = spec_of(bdir)
            langs = spec.get("languages") or list(reg["languages"])
            lines.append(f"### `{key}` — {spec['benchmark'].get('title', key)}\n")
            if spec["benchmark"].get("invariant"):
                lines.append(f"**Invariant.** {spec['benchmark']['invariant']}\n")
            if spec["benchmark"].get("row"):
                lines.append(f"**Row.** {spec['benchmark']['row']}\n")
            if spec.get("workload"):
                pairs = ", ".join(f"`{k}={v}`" for k, v in spec["workload"].items())
                lines.append(f"**Workload.** {pairs}\n")
            lines.append("| row (unit) | " + " | ".join(titles.get(l, l) for l in langs) + " |")
            lines.append("|---|" + "---|" * len(langs))
            for rname, rspec in spec.get("rows", {}).items():
                cells = [fmt_cell(runs_by, key, l, machine, rname, rspec) for l in langs]
                lines.append(f"| `{rname}` ({rspec.get('unit', '')}) | " + " | ".join(cells) + " |")
            lines.append("")
            legend = [f"`{rn}` ({rs.get('unit', '')}) — {rs['about']}" for rn, rs in spec.get("rows", {}).items() if rs.get("about")]
            if legend:
                lines.append("_Rows:_ " + "; ".join(legend) + ".")
                lines.append("")
            skipped = {
                l: runs_by[(key, l, machine)]["notes"]
                for l in langs
                if (key, l, machine) in runs_by and runs_by[(key, l, machine)]["notes"].startswith("SKIPPED")
            }
            if skipped:
                lines.append("Not measured here:")
                for l, why in skipped.items():
                    lines.append(f"- **{titles.get(l, l)}** — {why}")
                lines.append("")
    return "\n".join(lines)


def fmt_cell(runs_by, key, lang, machine, rname, rspec):
    row = runs_by.get((key, lang, machine))
    if row is None:
        return "—"
    if rname not in row["rows"]:
        if row["notes"].startswith("SKIPPED"):
            return "SKIPPED"
        return "—"
    cell = row["rows"][rname]
    return fmt(cell["unit"] or rspec.get("unit", ""), cell["value"], cell["samples"])


# ── html ─────────────────────────────────────────────────────────────

def esc(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def render_html(runs, reg, benches):
    out = ["<!doctype html>", '<html lang="en"><head><meta charset="utf-8">',
           "<title>Avra benchmark report</title>",
           "<style>body{font:15px/1.5 system-ui,sans-serif;max-width:60rem;margin:2rem auto;padding:0 1rem}"
           "table{border-collapse:collapse;margin:1rem 0}th,td{border:1px solid #ccc;padding:.3rem .6rem;text-align:right}"
           "td:first-child,th:first-child{text-align:left}code{background:#f4f4f4;padding:.1rem .3rem}"
           "h2{border-top:1px solid #ddd;padding-top:1rem}</style></head><body>"]
    out.append("<h1>Avra benchmark report</h1>")
    out.append("<p>Generated by <code>benchmarks/run.sh --report</code> from "
               "<code>benchmarks/results/runs.jsonl</code>. Never hand-edit.</p>")
    runs_by = run_map(runs)
    titles = language_titles(reg)
    versions = versions_by_machine(runs, reg)
    machines = sorted({row["machine"] for row in runs})
    for machine in machines:
        out.append(f"<h2>Machine <code>{esc(machine)}</code></h2>")
        out.append("<table><tr><th>language</th><th>version</th></tr>")
        for lang in reg["languages"]:
            v = versions.get((machine, lang))
            if v:
                out.append(f"<tr><td>{esc(titles.get(lang, lang))}</td><td><code>{esc(v)}</code></td></tr>")
        out.append("</table>")
        for key, bdir in benches:
            spec = spec_of(bdir)
            langs = spec.get("languages") or list(reg["languages"])
            out.append(f"<h3><code>{esc(key)}</code> — {esc(spec['benchmark'].get('title', key))}</h3>")
            if spec["benchmark"].get("invariant"):
                out.append(f"<p><b>Invariant.</b> {esc(spec['benchmark']['invariant'])}</p>")
            if spec["benchmark"].get("row"):
                out.append(f"<p><b>Row.</b> {esc(spec['benchmark']['row'])}</p>")
            if spec.get("workload"):
                pairs = ", ".join(f"<code>{esc(k)}={esc(str(v))}</code>" for k, v in spec["workload"].items())
                out.append(f"<p><b>Workload.</b> {pairs}</p>")
            out.append("<table><tr><th>row (unit)</th>" + "".join(f"<th>{esc(titles.get(l, l))}</th>" for l in langs) + "</tr>")
            for rname, rspec in spec.get("rows", {}).items():
                cells = [fmt_cell(runs_by, key, l, machine, rname, rspec) for l in langs]
                out.append(f"<tr><td><code>{esc(rname)}</code> ({esc(rspec.get('unit', ''))})</td>"
                           + "".join(f"<td>{esc(c)}</td>" for c in cells) + "</tr>")
            out.append("</table>")
            skipped = {
                l: runs_by[(key, l, machine)]["notes"]
                for l in langs
                if (key, l, machine) in runs_by and runs_by[(key, l, machine)]["notes"].startswith("SKIPPED")
            }
            if skipped:
                out.append("<p>Not measured here:</p><ul>")
                for l, why in skipped.items():
                    out.append(f"<li><b>{esc(titles.get(l, l))}</b> — {esc(why)}</li>")
                out.append("</ul>")
    out.append("</body></html>")
    return "\n".join(out) + "\n"


def render(runs=None):
    runs = load_runs() if runs is None else runs
    reg = registry()
    benches = bench_dirs()
    md = HEADER + "\n" + machine_sections(runs, reg, benches)
    # A sentence naming the row count so a reader sees the projection's size.
    md += f"\n_Projected from {len(runs)} stored row(s)._\n"
    return md, render_html(runs, reg, benches)


def write(out=REPORT, runs=None):
    md, html = render(runs)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "results.md"), "w") as f:
        f.write(md)
    with open(os.path.join(out, "index.html"), "w") as f:
        f.write(html)
    return md, html


def check(committed=REPORT):
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        md, html = write(d)
        ok = True
        for name, fresh in (("results.md", md), ("index.html", html)):
            path = os.path.join(committed, name)
            was = open(path).read() if os.path.isfile(path) else None
            if was != fresh:
                ok = False
                print(f"report: {name} DIFFERS from the committed report", file=sys.stderr)
        return ok


if __name__ == "__main__":
    args = sys.argv[1:]
    if "--check" in args:
        sys.exit(0 if check() else 1)
    out = REPORT
    if "--out" in args:
        out = args[args.index("--out") + 1]
    write(out)
    print(f"report: wrote {out}/results.md and {out}/index.html")
